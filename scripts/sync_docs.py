# sync
# --------------------------------------------------------------------------

def sync(
    config: dict[str, Any],
    content_out: Path = CONTENT_UPSTREAM,
    assets_out: Path = ASSETS_UPSTREAM,
    repo_root: Path = REPO_ROOT,
) -> dict[str, Any]:
    """Regenerate L2. Byte-stable on repeated runs with the same pins.

    `repo_root` anchors every repo-relative path: upstream clones
    (`projects.*.repo`) and curated translation sources
    (`projects.*.translations.*.source`). Tests pass a tmp root so the real
    viewer tree is never touched.
    """
    rules = normalize_rules(config)
    projects: dict[str, Any] = config["projects"]

    # --- resolve pins first (fail fast before touching L2) ----------------
    pins: dict[str, dict[str, str]] = {}
    for name, project in projects.items():
        repo = (repo_root / project["repo"]).resolve()
        if not (repo / ".git").exists():
            raise SyncError(f"{name}: clone not found at {repo}")
        assert_pristine(repo, name)
        sha = resolve_sha(repo, project["ref"])
        pins[name] = {
            "repo_path": str(repo),
            "sha": sha,
            "commit_date": commit_iso(repo, sha),
        }

    # --- phase A: compute every output in memory (fail-fast on drift) -----
    provenance_files: dict[str, dict[str, Any]] = {}
    pending_files: list[tuple[Path, str]] = []
    pending_assets: list[tuple[Path, Path]] = []
    sidecar_pages: dict[str, dict[str, Any]] = {}
    report: dict[str, Any] = {"projects": {}, "skipped": []}

    for name, project in projects.items():
        validate_selection(name, project)
        pin = pins[name]
        repo = Path(pin["repo_path"])
        sha = pin["sha"]
        commit_date = pin["commit_date"]
        locale_dirs: dict[str, str] = project["locale_dirs"]
        overlays: list[dict[str, Any]] = project.get("overlays") or []
        included_slugs = {
            f"{name}/{entry['path'][: -len(MD_EXT)]}" for entry in project["include"]
        }

        stats: dict[str, list[str]] = {
            "included_slugs": sorted(included_slugs),
            "asset_copies": [],
            "images": [],
            "dangling_slugs": [],
            "github_links": [],
            "escapes": [],
            "missing_targets": [],
            "overlays_applied": [],
        }
        per_locale: dict[str, dict[str, int]] = {}

        for locale, locale_dir in locale_dirs.items():
            written = 0
            bytes_total = 0
            for entry in project["include"]:
                entry_path = entry["path"]
                source = repo / locale_dir / entry_path
                if not source.is_file():
                    report["skipped"].append(
                        {
                            "project": name,
                            "locale": locale,
                            "path": entry_path,
                            "why": "source file missing in pinned clone",
                        }
                    )
                    continue
                raw = source.read_text(encoding="utf-8")
                body = strip_chrome(raw, rules)
                body, applied = apply_overlays(body, overlays, locale, entry_path)
                stats["overlays_applied"].extend(applied)
                rewriter = Rewriter(
                    project=name,
                    repo=repo,
                    sha=sha,
                    web_base=project.get("web_base", ""),
                    locale_dirs=locale_dirs,
                    source_dir=posixpath.dirname(posixpath.join(locale_dir, entry_path)),
                    assets_out=assets_out,
                    stats=stats,
                )
                body = rewriter.rewrite(body)

                slug = f"{name}/{entry_path[: -len(MD_EXT)]}"
                fallback_title = entry_path[: -len(MD_EXT)].replace("/", " · ").replace("-", " ")
                title = resolve_title(entry, locale, body, fallback_title)
                order = entry["order"]
                note = entry.get("note")
                if isinstance(note, dict):
                    note = note.get(locale)
                note = str(note).strip() if note else None

                page = assemble_page(
                    fields=[
                        ("title", title),
                        ("slug", slug),
                        ("category", str(entry["category"])),
                        ("order", str(int(order))),
                        ("last_verified", commit_date[:10]),
                    ],
                    banner=BANNER_TEMPLATE.format(project=name, sha=sha[:12]),
                    note=note,
                    body=body,
                )
                dest = content_out / name / locale / entry_path
                pending_files.append((dest, page))
                written += 1
                bytes_total += len(page.encode("utf-8"))

                provenance_files.setdefault(slug, {})[locale] = {
                    "repo": name,
                    "source_path": f"{locale_dir}/{entry_path}",
                    "sha": sha,
                    "commit_date": commit_date,
                    "synced_at": commit_date,
                    "locale": locale,
                    "kind": "upstream",
                }
                page_entry = sidecar_pages.setdefault(
                    slug,
                    {
                        "slug": slug,
                        "titles": {},
                        "category": str(entry["category"]),
                        "order": int(order),
                        "lastVerified": commit_date[:10],
                        "locales": [],
                        "provenance": {
                            "repo": name,
                            "source_path": f"{locale_dir}/{entry_path}",
                            "sha": sha,
                            "commit_date": commit_date,
                        },
                    },
                )
                page_entry["titles"][locale] = title
                page_entry["locales"] = sorted(page_entry["titles"])
            per_locale[locale] = {"files": written, "raw_bytes": bytes_total}

        # --- curated translations (W3 prep): our layer, re-sync-proof -------
        # Published through the SAME phase-A/phase-B path as upstream pages:
        # the slot is recomputed from the curated source every run, so the
        # project wipe can never lose it. Missing curated file = warning.
        translations_published: list[str] = []
        for locale, entries in (project.get("translations") or {}).items():
            if locale in locale_dirs:
                raise SyncError(
                    f"{name}: translation locale {locale!r} collides with an "
                    f"upstream mirror in locale_dirs — translations are for "
                    f"locales the upstream does not ship"
                )
            include_entries = {entry["path"]: entry for entry in project["include"]}
            for entry in entries:
                source_of = entry.get("source_of")
                if source_of not in include_entries:
                    raise SyncError(
                        f"{name}: translation source_of {source_of!r} is not "
                        f"an included page — fix sync-config.yaml"
                    )
                source_rel = entry.get("source")
                if not source_rel:
                    raise SyncError(
                        f"{name}: translation for {source_of!r} lacks `source`"
                    )
                curated = repo_root / source_rel
                if not curated.is_file():
                    report["skipped"].append(
                        {
                            "project": name,
                            "locale": locale,
                            "path": source_rel,
                            "why": "curated translation file missing",
                        }
                    )
                    continue
                meta, body = split_frontmatter(
                    curated.read_text(encoding="utf-8"), str(curated)
                )
                slug = f"{name}/{source_of[: -len(MD_EXT)]}"
                en_entry = include_entries[source_of]
                fallback = source_of[: -len(MD_EXT)].replace("-", " ")
                title = meta.get("title") or first_h1(body) or fallback
                page = assemble_page(
                    fields=[
                        ("title", re.sub(r"\s+", " ", title).strip()),
                        ("slug", slug),
                        ("category", str(en_entry["category"])),
                        ("order", str(int(en_entry["order"]))),
                        ("last_verified", commit_date[:10]),
                    ]
                    + [
                        (key, value)
                        for key, value in meta.items()
                        if key
                        not in {"title", "slug", "category", "order", "last_verified"}
                    ],
                    banner=CURATED_BANNER_TEMPLATE.format(
                        project=name, sha=sha[:12], source=source_rel
                    ),
                    note=None,
                    body=body,
                )
                slot = content_out / name / locale / source_of
                pending_files.append((slot, page))
                translations_published.append(f"{locale}/{source_of}")
                provenance_files.setdefault(slug, {})[locale] = {
                    "repo": name,
                    "source_path": source_rel,
                    "sha": sha,
                    "source_sha": sha,
                    "commit_date": commit_date,
                    "synced_at": commit_date,
                    "locale": locale,
                    "kind": "curated-translation",
                    **(
                        {"translator_note": str(entry["translator_note"])}
                        if entry.get("translator_note")
                        else {}
                    ),
                }
                page_entry = sidecar_pages.setdefault(
                    slug,
                    {
                        "slug": slug,
                        "titles": {},
                        "category": str(en_entry["category"]),
                        "order": int(en_entry["order"]),
                        "lastVerified": commit_date[:10],
                        "locales": [],
                        "provenance": {
                            "repo": name,
                            "source_path": f"{locale_dirs[next(iter(locale_dirs))]}/{source_of}",
                            "sha": sha,
                            "commit_date": commit_date,
                        },
                    },
                )
                page_entry["titles"][locale] = re.sub(r"\s+", " ", title).strip()
                page_entry["locales"] = sorted(page_entry["titles"])
                page_entry.setdefault("kinds", {})[locale] = "curated-translation"

        pending_assets.extend(stats["asset_copies"])

        report["projects"][name] = {
            "sha": sha,
            "commit_date": commit_date,
            "locales": per_locale,
            "translations": sorted(translations_published),
            "images": sorted(stats["images"]),
            "dangling_slugs": sorted(set(stats["dangling_slugs"])),
            "github_links": sorted(set(stats["github_links"])),
            "escapes": sorted(set(stats["escapes"])),
            "missing_targets": sorted(set(stats["missing_targets"])),
            "overlays_applied": stats["overlays_applied"],
        }

    # --- phase B: wipe L2 and write everything (fail-fast happened above) --
    # Full wipe -> stale selections can never leak into the corpus (§6.6).
    if content_out.exists():
        for child in content_out.iterdir():
            if child.name in (PROVENANCE_NAME, SIDECAR_NAME):
                continue
            shutil.rmtree(child) if child.is_dir() else child.unlink()
    content_out.mkdir(parents=True, exist_ok=True)
    if assets_out.exists():
        for child in assets_out.iterdir():
            if child.name not in projects:
                shutil.rmtree(child) if child.is_dir() else child.unlink()
    for name in projects:
        shutil.rmtree(assets_out / name, ignore_errors=True)
    assets_out.mkdir(parents=True, exist_ok=True)
    for dest, page in pending_files:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(page, encoding="utf-8")
    for source, dest in pending_assets:
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, dest)

    # --- manifests ---------------------------------------------------------
    for page in sidecar_pages.values():
        page["locales"] = sorted(page["locales"])

    now_pin_dates = {name: pin["commit_date"] for name, pin in pins.items()}
    provenance = {
        "version": 1,
        "generated_by": "scripts/sync_docs.py",
        # Deterministic "sync time": the pinned commits' dates. Wall-clock
        # would break the byte-stable re-sync gate; drift is visible via SHA.
        "synced_at": max(now_pin_dates.values()) if now_pin_dates else None,
        "projects": {
            name: {
                "repo": projects[name]["repo"],
                "ref": projects[name]["ref"],
                "sha": pins[name]["sha"],
                "commit_date": pins[name]["commit_date"],
            }
            for name in projects
        },
        "files": dict(sorted(provenance_files.items())),
    }
    sidecar = {
        "version": 1,
        "generated_by": "scripts/sync_docs.py",
        "source_shas": {name: pins[name]["sha"] for name in projects},
        # Field shape mirrors viewer DocPage (manifest.ts): slug, titles,
        # category, order, lastVerified, locales + per-page provenance.
        "pages": [sidecar_pages[slug] for slug in sorted(sidecar_pages)],
    }
    (content_out / PROVENANCE_NAME).write_text(
        json.dumps(provenance, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    (content_out / SIDECAR_NAME).write_text(
        json.dumps(sidecar, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    report["pins"] = {name: pins[name]["sha"] for name in pins}
    report["pages"] = len(sidecar_pages)
    report["skipped"].sort(key=lambda item: (item["project"], item["locale"], item["path"]))
    return report


def print_sync_report(report: dict[str, Any]) -> None:
    for name, info in report["projects"].items():
        locales = ", ".join(
            f"{loc}: {stat['files']} files / {stat['raw_bytes']} B"
            for loc, stat in info["locales"].items()
        )
        print(f"[{name}] pinned {info['sha'][:12]} ({info['commit_date'][:10]}) — {locales}")
        if info["translations"]:
            print(f"  curated translations published: {len(info['translations'])}")
            for slug in info["translations"]:
                print(f"    - {slug}")
        if info["images"]:
            print(f"  vendored images ({len(info['images'])}):")
            for image in info["images"]:
                print(f"    - {image}")
        if info["dangling_slugs"]:
            print(
                f"  links to pages outside the selection "
                f"({len(info['dangling_slugs'])} unique slugs — W2 may include or overlay):"
            )
            for slug in info["dangling_slugs"]:
                print(f"    - {slug}")
        if info["github_links"]:
            print(f"  links rewritten to pinned GitHub URLs: {len(info['github_links'])}")
        if info["escapes"]:
            print(f"  links escaping the clone (left as-is): {info['escapes']}")
        if info["missing_targets"]:
            print(f"  link targets missing upstream (left as-is): {info['missing_targets']}")
        if info["overlays_applied"]:
            print(f"  overlays applied: {len(info['overlays_applied'])}")
    for skip in report["skipped"]:
        print(f"[skip] {skip['project']}/{skip['locale']}/{skip['path']}: {skip['why']}")
    print(
        f"total: {report['pages']} pages, "
        f"provenance + sidecar written to {CONTENT_UPSTREAM}"
    )


