def check_drift(config: dict[str, Any]) -> dict[str, Any]:
    """Report-only comparison of pinned refs vs clone HEADs (contract §7)."""
    report: dict[str, Any] = {"projects": {}}
    for name, project in config["projects"].items():
        repo = (REPO_ROOT / project["repo"]).resolve()
        pinned = resolve_sha(repo, project["ref"])
        head = resolve_sha(repo, "HEAD")
        dirty = tracked_dirty(repo)
        new_docs: list[str] = []
        status = "OK"
        if head != pinned:
            status = "DRIFT"
            log = run_git(
                repo, "log", "--oneline", "--", *project["locale_dirs"].values(),
                f"{pinned}..{head}",
            )
            new_docs = log.splitlines()[:10]
        report["projects"][name] = {
            "pinned": pinned,
            "head": head,
            "drift": head != pinned,
            "dirty": dirty,
            "new_doc_commits": new_docs,
        }
        print(f"[{name}] pin {pinned[:12]} vs HEAD {head[:12]}: {status}")
        for line in new_docs:
            print(f"    new: {line}")
        if dirty:
            print(f"    WARNING: clone has {len(dirty)} tracked modifications")
    return report


