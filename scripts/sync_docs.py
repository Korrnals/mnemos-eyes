#!/usr/bin/env python3
"""Docs upstream import pipeline — layer L1 (ARCHCOM-7 contract 2026-09-23).

Reads local upstream clones pinned by SHA (L0), applies the declarative
selection/normalization/overlay rules from scripts/sync-config.yaml, and
regenerates the L2 corpus in the viewer docs tree:

  viewer/src/features/docs/content/upstream/<project>/<locale>/<path>.md
  viewer/src/features/docs/content/upstream/provenance.json
  viewer/src/features/docs/content/upstream/manifest.sidecar.json
  viewer/src/features/docs/assets/upstream/<project>/<repo-relative-path>

Curated translations (our layer, e.g. mnemos-mesh ru): authored under
viewer/src/features/docs/curated/<project>/<locale>/<path>.md (outside the
wiped zone) and republished into the L2 locale slot on every sync —
provenance kind "curated-translation". A missing curated file is a warning,
never a failure.

L2 is GENERATED — never hand-edited. Style fixes go through `overlays` in
sync-config.yaml; an overlay anchor that no longer matches fails the sync
(upstream drift signal, contract §6.3). The corpus is byte-stable across
re-runs on the same pins (idempotency gate): no wall-clock values are
written — `synced_at` carries the pinned commit's ISO date instead.

Usage:
  python3 scripts/sync_docs.py sync           regenerate L2 (default)
  python3 scripts/sync_docs.py --check-drift  compare pins with clone HEADs
  python3 scripts/sync_docs.py check-drift    (same, subcommand form)

Exit codes: 0 ok, 1 sync/drift error (bad pin, dirty clone, overlay drift,
config sanity).
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import posixpath
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:  # pragma: no cover - environment guard
    sys.exit("sync_docs: PyYAML is required (python3 -m pip install pyyaml)")

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
DEFAULT_CONFIG = SCRIPT_DIR / "sync-config.yaml"
DOCS_DIR = REPO_ROOT / "viewer" / "src" / "features" / "docs"
CONTENT_UPSTREAM = DOCS_DIR / "content" / "upstream"
ASSETS_UPSTREAM = DOCS_DIR / "assets" / "upstream"
PROVENANCE_NAME = "provenance.json"
SIDECAR_NAME = "manifest.sidecar.json"
BANNER_TEMPLATE = (
    "<!-- GENERATED by sync_docs from {project}@{sha} "
    "— правки через sync-config.yaml overlay -->"
)
CURATED_BANNER_TEMPLATE = (
    "<!-- GENERATED by sync_docs (curated translation of {project}@{sha}) from "
    "{source} — правки в curated-файле, не здесь -->"
)
IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp", ".avif", ".ico"}
MD_EXT = ".md"
HEADING1_RE = re.compile(r"^#\s+(.+?)\s*#*\s*$")
LINK_RE = re.compile(r"(?<!\!)\[([^\]]*)\]\(([^)\s]+)\)")
IMAGE_RE = re.compile(r"!\[([^\]]*)\]\(([^)\s]+)\)")
EXTERNAL_TARGET_RE = re.compile(r"^(https?:)?//|^mailto:|^data:")

# Defaults applied when sync-config.yaml omits the `normalize` section.
DEFAULT_NORMALIZE: dict[str, Any] = {
    "strip_lines_matching": [],
    "strip_html_comment_lines": True,
    "collapse_blank_lines": 2,
}


class SyncError(RuntimeError):
    """Fatal pipeline error (bad pin, dirty clone, overlay drift, config)."""


# --------------------------------------------------------------------------
# git plumbing (L0)
# --------------------------------------------------------------------------

def run_git(repo: Path, *args: str) -> str:
    proc = subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True
    )
    if proc.returncode != 0:
        raise SyncError(
            f"git -C {repo} {' '.join(args)} failed: {proc.stderr.strip()}"
        )
    return proc.stdout.strip()


def resolve_sha(repo: Path, ref: str) -> str:
    """Full SHA for a ref (SHA, branch, tag) at the current clone state."""
    sha = run_git(repo, "rev-parse", "--verify", f"{ref}^{{commit}}")
    if not re.fullmatch(r"[0-9a-f]{40}", sha):
        raise SyncError(f"{repo}: ref {ref!r} did not resolve to a commit SHA")
    return sha


def tracked_dirty(repo: Path) -> list[str]:
    """Tracked modifications only — untracked files don't affect the SHA."""
    out = run_git(repo, "status", "--porcelain")
    return [
        line
        for line in out.splitlines()
        if line.strip() and not line.startswith("??")
    ]


def assert_pristine(repo: Path, project: str) -> None:
    dirty = tracked_dirty(repo)
    if dirty:
        preview = "\n".join(dirty[:10])
        raise SyncError(
            f"{project}: clone {repo} has tracked modifications — refusing to "
            f"sync so the pinned SHA stays honest. Clean or commit there "
            f"first:\n{preview}"
        )


def commit_iso(repo: Path, sha: str) -> str:
    return run_git(repo, "log", "-1", "--format=%cI", sha)


# --------------------------------------------------------------------------
# config
# --------------------------------------------------------------------------

def load_config(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise SyncError(f"config not found: {path}")
    config = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(config, dict) or not config.get("projects"):
        raise SyncError(f"{path}: expected a non-empty `projects:` mapping")
    for name, project in config["projects"].items():
        for key in ("repo", "ref", "locale_dirs", "include"):
            if key not in project:
                raise SyncError(f"{path}: project {name} lacks `{key}`")
        if not project["locale_dirs"]:
            raise SyncError(f"{path}: project {name} has empty locale_dirs")
    return config


def validate_selection(project_name: str, project: dict[str, Any]) -> None:
    """Contract §6.6: exclude entries must never overlap include entries."""
    included = {entry["path"] for entry in project["include"]}
    for rule in project.get("exclude", []) or []:
        excluded = rule["path"].rstrip("/")
        for inc in included:
            if inc == excluded or inc.startswith(excluded + "/"):
                raise SyncError(
                    f"{project_name}: include {inc!r} overlaps exclude "
                    f"{rule['path']!r} — fix sync-config.yaml"
                )


def normalize_rules(config: dict[str, Any]) -> dict[str, Any]:
    rules = dict(DEFAULT_NORMALIZE)
    rules.update(config.get("normalize") or {})
    return rules


# --------------------------------------------------------------------------
# L1 text transforms
# --------------------------------------------------------------------------

def strip_chrome(text: str, rules: dict[str, Any]) -> str:
    """Cut upstream chrome: language switchers and pure html-comment lines."""
    kept: list[str] = []
    patterns = rules.get("strip_lines_matching") or []
    strip_comments = bool(rules.get("strip_html_comment_lines"))
    for line in text.splitlines():
        stripped = line.strip()
        if any(fnmatch.fnmatch(stripped, pat) for pat in patterns):
            continue
        if (
            strip_comments
            and stripped.startswith("<!--")
            and stripped.endswith("-->")
            and len(stripped) > 7
        ):
            continue
        kept.append(line)
    collapsed = re.sub(r"\n{3,}", "\n" * int(rules.get("collapse_blank_lines", 2)), "\n".join(kept))
    return collapsed.strip("\n") + "\n"


def apply_overlays(
    body: str, overlays: list[dict[str, Any]], locale: str, entry_path: str
) -> tuple[str, list[str]]:
    """Anchored find/replace. Zero or 2+ matches of the anchor = DRIFT fail."""
    applied: list[str] = []
    for rule in overlays or []:
        if rule.get("file") != f"{locale}/{entry_path}":
            continue
        find = rule["find"]
        count = body.count(find)
        if count != 1:
            raise SyncError(
                f"overlay DRIFT on {locale}/{entry_path}: anchor matched "
                f"{count} times (expected 1) — upstream changed, update the "
                f"rule. Reason on record: {rule.get('reason', 'n/a')}"
            )
        body = body.replace(find, rule["replace"])
        applied.append(rule.get("reason", find[:40]))
    return body, applied


def split_anchor(target: str) -> tuple[str, str]:
    """`page.md#sec` -> (`page.md`, `#sec`); pure anchors -> (``, `#sec`)."""
    if target.startswith("#"):
        return "", target
    path, sep, anchor = target.partition("#")
    return path, (sep + anchor)


def page_slug_for(project: str, locale_dirs: dict[str, str], resolved: str) -> str | None:
    """If `resolved` (repo-relative) is a docs locale page, its board slug."""
    for locale_dir in locale_dirs.values():
        prefix = locale_dir.rstrip("/") + "/"
        if resolved.startswith(prefix) and resolved.endswith(MD_EXT):
            return f"{project}/{resolved[len(prefix):][: -len(MD_EXT)]}"
    return None


def first_h1(body: str) -> str | None:
    for line in body.splitlines():
        match = HEADING1_RE.match(line.strip())
        if match:
            return match.group(1).strip()
    return None


def split_frontmatter(text: str, where: str) -> tuple[dict[str, str], str]:
    """Split a leading `---` block of `key: value` lines (viewer-compatible).

    Returns (fields, body). Curated translations are writer-authored, so a
    malformed frontmatter block is an authoring bug -> loud SyncError.
    """
    if not text.startswith("---\n"):
        return {}, text
    lines = text.splitlines()
    close = next(
        (i for i in range(1, len(lines)) if lines[i].strip() == "---"), None
    )
    if close is None:
        raise SyncError(f"{where}: frontmatter opened but never closed")
    fields: dict[str, str] = {}
    for line in lines[1:close]:
        stripped = line.strip()
        if not stripped:
            continue
        key, sep, value = stripped.partition(":")
        if not key.strip() or not sep or not value.strip():
            raise SyncError(f"{where}: malformed frontmatter line {line!r}")
        fields[key.strip()] = value.strip().strip("'\"")
    return fields, "\n".join(lines[close + 1 :])


class Rewriter:
    """Rewrites markdown links/images of one source file (contract §6.1/§6.4)."""

    def __init__(
        self,
        *,
        project: str,
        repo: Path,
        sha: str,
        web_base: str,
        locale_dirs: dict[str, str],
        source_dir: str,
        assets_out: Path,
        stats: dict[str, list[Any]],
    ) -> None:
        self.project = project
        self.repo = repo
        self.sha = sha
        self.web_base = web_base
        self.locale_dirs = locale_dirs
        self.source_dir = source_dir  # repo-relative dir of the source file
        self.assets_out = assets_out
        self.stats = stats

    def _resolve(self, target: str) -> str | None:
        """Repo-relative resolution; None when the link escapes the clone."""
        resolved = posixpath.normpath(posixpath.join(self.source_dir, target))
        if resolved.startswith(".."):
            self.stats["escapes"].append(target)
            return None
        return resolved

    def _github_url(self, resolved: str, anchor: str) -> str | None:
        """Pinned blob URL for repo files outside the docs locale pages."""
        if not self.web_base:
            return None
        if not (self.repo / resolved).is_file():
            self.stats["missing_targets"].append(resolved)
            return None
        return f"{self.web_base.format(sha=self.sha)}/{resolved}{anchor}"

    def rewrite(self, body: str) -> str:
        body = IMAGE_RE.sub(self._sub_image, body)
        return LINK_RE.sub(self._sub_link, body)

    def _sub_image(self, match: re.Match[str]) -> str:
        alt, target = match.group(1), match.group(2)
        if EXTERNAL_TARGET_RE.match(target) or target.startswith("/"):
            return match.group(0)
        path, anchor = split_anchor(target)
        if not path:
            return match.group(0)
        resolved = self._resolve(path)
        if resolved is None:
            return match.group(0)
        ext = Path(resolved).suffix.lower()
        source = self.repo / resolved
        if ext not in IMAGE_EXTS or not source.is_file():
            self.stats["missing_targets"].append(resolved)
            return match.group(0)
        dest = self.assets_out / self.project / resolved
        self.stats["asset_copies"].append((source, dest))
        self.stats["images"].append(resolved)
        return f"![{alt}](upstream/{self.project}/{resolved}{anchor})"

    def _sub_link(self, match: re.Match[str]) -> str:
        text, target = match.group(1), match.group(2)
        if EXTERNAL_TARGET_RE.match(target) or target.startswith("/"):
            return match.group(0)
        path, anchor = split_anchor(target)
        if not path:
            return match.group(0)  # pure in-page anchor
        resolved = self._resolve(path)
        if resolved is None:
            return match.group(0)  # cross-clone hop (e.g. mesh -> mnemos): keep
        slug = page_slug_for(self.project, self.locale_dirs, resolved)
        if slug is not None:
            if slug not in self.stats["included_slugs"]:
                self.stats["dangling_slugs"].append(slug)
            return f"[{text}]({slug}{anchor})"
        url = self._github_url(resolved, anchor)
        if url is None:
            return match.group(0)  # missing upstream file: keep, warn
        self.stats["github_links"].append(resolved)
        return f"[{text}]({url})"


# --------------------------------------------------------------------------
# page assembly
# --------------------------------------------------------------------------

def resolve_title(entry: dict[str, Any], locale: str, body: str, fallback: str) -> str:
    title = entry.get("title")
    if isinstance(title, dict):
        title = title.get(locale)
    elif isinstance(title, str):
        pass
    else:
        title = None
    if not title:
        title = first_h1(body) or fallback
    return re.sub(r"\s+", " ", str(title)).strip()


def frontmatter_block(fields: list[tuple[str, str]]) -> str:
    lines = ["---"]
    lines.extend(f"{key}: {value}" for key, value in fields)
    lines.append("---")
    return "\n".join(lines)


def assemble_page(
    *,
    fields: list[tuple[str, str]],
    banner: str,
    note: str | None,
    body: str,
) -> str:
    parts = [frontmatter_block(fields), "", banner, ""]
    if note:
        parts.extend([f"> {note}", ""])
    parts.append(body.rstrip("\n"))
    return "\n".join(parts) + "\n"


